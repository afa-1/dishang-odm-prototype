/* Project-module browser checks. Uses a fresh browser context; no user data is touched.
 * PROJECT_TEST_URL defaults to the running Vite server. PLAYWRIGHT_MODULE and
 * CHROME_PATH can override the local runtime paths for another workstation.
 */
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const base = process.env.PROJECT_TEST_URL || 'http://127.0.0.1:4173'
const out = process.env.PROJECT_TEST_OUTPUT || '/Users/mac/Desktop/迪尚ODM/tmp/project-module-check'
const errors = []
let assertions = 0
