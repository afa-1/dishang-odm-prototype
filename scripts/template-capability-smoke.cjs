/* Isolated prototype checks: does not read or modify the user's browser profile. */
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const base = process.env.PROJECT_TEST_URL || 'http://127.0.0.1:4173'
const out = '/Users/mac/Desktop/迪尚ODM/tmp/template-capability-check'
let count = 0
function check(value, message) { assert.ok(value, message); count++; console.log('PASS', message) }
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    await fs.mkdir(out, { recursive: true })
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(`${base}/?view=projects`)
    const templates = page.getByRole('region', { name: '项目模板' })
    check(await templates.getByRole('button').count() === 5, 'five project templates')
    const legacy = await page.evaluate(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1'))[0])
    check(legacy.teams.includes('趋势企划天团') && !legacy.experts.includes('趋势企划天团'), 'legacy team migrated out of expert field')
    check(legacy.tasks[0].context.experts.includes('趋势企划天团'), 'migration does not rewrite historical task snapshots')
    await templates.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `${out}/01-templates.png` })
    for (const name of ['客户需求开发', '自主款式开发', '材料驱动开发', '趋势研究', '服装企划']) {
      await templates.getByRole('button', { name: new RegExp(name) }).click()
      const dialog = page.getByRole('dialog')
      check((await dialog.getByLabel('项目目标 / 指令', { exact: true }).inputValue()).includes('内部最终确认'), `${name} carries instruction and internal decision boundary`)
      check((await dialog.getByLabel('项目名称 *', { exact: true }).inputValue()) === '', `${name} does not invent a project or client`)
      await dialog.getByRole('button', { name: '取消', exact: true }).click()
    }
    await templates.getByRole('button', { name: /材料驱动开发/ }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('项目名称 *', { exact: true }).fill('模板测试 · 轻量材料')
    await dialog.getByLabel('季节', { exact: true }).fill('2027 春夏')
    await dialog.getByRole('button', { name: '北辰服饰（示例）', exact: true }).click()
    await dialog.getByLabel('项目目标 / 指令', { exact: true }).fill('我的自定义指令')
    await dialog.getByLabel('项目模板', { exact: true }).selectOption('trend-research')
    check(await dialog.getByRole('button', { name: '创建项目', exact: true }).isDisabled(), 'template replacement blocks submit until resolved')
    await dialog.getByRole('button', { name: '保留当前配置', exact: true }).click()
    check(await dialog.getByLabel('项目目标 / 指令', { exact: true }).inputValue() === '我的自定义指令', 'cancel replacement preserves edited instructions')
    await dialog.getByLabel('项目模板', { exact: true }).selectOption('trend-research')
    await dialog.getByRole('button', { name: '确认应用模板', exact: true }).click()
    check(await dialog.getByLabel('季节', { exact: true }).inputValue() === '2027 春夏', 'replacement preserves basic information')
    check(await dialog.getByRole('button', { name: '北辰服饰（示例）', exact: true }).getAttribute('aria-pressed') === 'true', 'replacement preserves customer association')
    await dialog.locator('summary').filter({ hasText: '专家团' }).click()
    check(await dialog.getByRole('button', { name: '趋势企划专家团', exact: true }).getAttribute('aria-pressed') === 'true', 'template equips team separately')
    await dialog.screenshot({ path: `${out}/02-template-form.png` })
    await dialog.getByRole('button', { name: '创建项目', exact: true }).click()
    await page.getByRole('heading', { name: '模板测试 · 轻量材料', exact: true }).waitFor()
    const id = new URL(page.url()).searchParams.get('project')
    const read = () => page.evaluate(id => JSON.parse(localStorage.getItem('hyy-odm-projects-v1')).find(p => p.id === id), id)
    let state = await read()
    check(state.templateId === 'trend-research' && state.experts.includes('趋势企划专家') && state.teams.includes('趋势企划专家团'), 'template and distinct expert/team persistence')
    check(!state.tasks.length && !state.assets.length && !state.handoffs.length, 'templates do not fabricate tasks or files or submit to PLM')
    await page.getByRole('navigation').getByRole('button', { name: '项目', exact: true }).click()
    await page.getByRole('button', { name: '新建项目', exact: true }).click()
    dialog = page.getByRole('dialog')
    check(await dialog.getByLabel('项目模板', { exact: true }).inputValue() === '' && await dialog.getByLabel('项目目标 / 指令', { exact: true }).inputValue() === '', 'blank creation does not reuse previous template')
    await page.keyboard.press('Escape')
    await page.goto(`${base}/?view=projects&project=${id}`)
    await page.reload()
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('这次需要完成什么？ *', { exact: true }).fill('研究风衣方向')
    await dialog.getByRole('button', { name: '创建任务', exact: true }).click()
    await page.getByRole('heading', { name: '研究风衣方向', exact: true }).waitFor()
    check((await read()).tasks[0].context.teams.includes('趋势企划专家团'), 'task captures team snapshot')
    await page.getByRole('button', { name: '调用技能 / 专家 / 专家团', exact: true }).click()
    dialog = page.getByRole('dialog')
    check(await dialog.locator('button[aria-pressed]').count() === 11, 'eight ODM skills plus three type controls')
    await dialog.getByRole('button', { name: /服装企划 PPT/ }).click()
    check(await dialog.getByRole('button', { name: '加入当前任务', exact: true }).isDisabled(), 'invocation requires instruction')
    await dialog.getByLabel('本次调用要求 *', { exact: true }).fill('基于已确认的研究做 12 页企划，先给大纲')
    await dialog.screenshot({ path: `${out}/03-skill-picker.png` })
    await dialog.getByRole('button', { name: '加入当前任务', exact: true }).click()
    state = await read()
    check(state.tasks[0].invocations[0].capability.id === 'odm-planning-ppt', 'invocation saves full capability contract')
    check(!state.skills.includes('服装企划 PPT'), 'temporary invocation does not change project defaults')
    await page.getByRole('button', { name: '生成演示工作底稿', exact: true }).click()
    check((await read()).assets[0].taskId === (await read()).tasks[0].id, 'working draft goes to same task and project')
    check((await read()).assets[0].revisions[0].name.endsWith('.md'), 'prototype does not disguise markdown as real PPT')
    await page.getByRole('button', { name: '查看工作底稿', exact: true }).click()
    dialog = page.getByRole('dialog')
    const downloaded = page.waitForEvent('download')
    await dialog.getByRole('button', { name: '下载此版本', exact: true }).click()
    const file = await downloaded
    const contents = await fs.readFile(await file.path(), 'utf8')
    check(contents.includes('12 页企划') && contents.includes('不是 AI 分析'), 'download has real request and honest prototype notice')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '调用技能 / 专家 / 专家团', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: '专家', exact: true }).click()
    check(await dialog.locator('button[aria-pressed]').count() === 7, 'four experts')
    await dialog.getByRole('button', { name: '专家团', exact: true }).click()
    check(await dialog.locator('button[aria-pressed]').count() === 6, 'three teams')
    await dialog.getByRole('button', { name: /材料驱动开发专家团/ }).click()
    check(await dialog.getByText('面辅料专家', { exact: true }).isVisible(), 'team shows actual members')
    await dialog.getByLabel('本次调用要求 *', { exact: true }).fill('结合材料特性给出开发建议')
    await dialog.locator('summary').filter({ hasText: '引用项目资产' }).click()
    await dialog.getByRole('checkbox').first().check()
    await dialog.getByRole('button', { name: '加入当前任务', exact: true }).click()
    state = await read()
    check(state.tasks[0].invocations[1].refs[0].revisionId === state.assets[0].adopted, 'mid-task reference freezes adopted revision')
    await page.reload()
    await page.getByRole('region', { name: '能力调用记录' }).waitFor()
    check((await read()).tasks[0].invocations.length === 2, 'multiple invocations survive reload')
    await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
    await page.waitForFunction(() => {
      const button = [...document.querySelectorAll('button')].find(b => b.textContent === '编辑信息')
      const panel = getComputedStyle(document.documentElement).getPropertyValue('--c-panel').trim().split(/\s+/).join(', ')
      return button && getComputedStyle(button).backgroundColor === `rgb(${panel})`
    })
    await page.screenshot({ path: `${out}/04-task-dark.png` })
    for (const width of [1280, 1024]) {
      await page.setViewportSize({ width, height: 900 })
      check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `no page overflow at ${width}`)
    }
    check(!errors.length, `no runtime errors: ${errors.join('; ')}`)
    console.log(`Completed ${count} assertions`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
