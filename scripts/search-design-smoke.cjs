const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { chromium } = require('/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
let n = 0
const check = (value, msg) => { assert.ok(value, msg); console.log('PASS', msg); n++ }
const out = '/Users/mac/Desktop/迪尚ODM/tmp/search-design-check'
;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('dialog', d => d.accept())
    await page.goto('http://127.0.0.1:4173/?view=projects&project=demo-summer-trench')
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('这次需要完成什么？ *', { exact: true }).fill('搜风衣参考并做款料方案')
    await dialog.getByRole('button', { name: '创建任务', exact: true }).click()
    await page.getByRole('heading', { name: '搜风衣参考并做款料方案', exact: true }).waitFor()
    const taskURL = page.url(), taskId = new URL(taskURL).searchParams.get('task')
    const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1')).find(p => p.id === 'demo-summer-trench'))
    const task = async () => (await read()).tasks.find(t => t.id === taskId)
    const originalCount = (await read()).assets.length
    await page.getByRole('button', { name: '搜款搜料', exact: true }).click()
    await page.getByLabel('检索描述', { exact: true }).fill('风衣')
    await page.getByRole('button', { name: '检索本地候选', exact: true }).click()
    check((await task()).searches[0].results.length >= 2, 'keyword search produces local candidates')
    check((await read()).assets.length === originalCount, 'result set does not automatically archive candidates')
    await page.getByTestId('search-workspace').getByRole('checkbox').nth(0).check()
    await page.getByTestId('search-workspace').getByRole('checkbox').nth(1).check()
    await page.getByRole('button', { name: '对比（2–4 项）', exact: true }).click()
    check(await page.getByRole('dialog').getByRole('heading', { name: '候选对比', exact: true }).isVisible(), 'candidate comparison')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '归档所选', exact: true }).click()
    const collectedCount = (await read()).assets.length
    await page.getByRole('button', { name: '归档所选', exact: true }).click()
    check((await read()).assets.length === collectedCount, 'repeated collection is deduplicated')
    await page.screenshot({ path: `${out}/01-search.png` })
    await page.getByRole('button', { name: '加入设计画布', exact: true }).click()
    await page.getByRole('heading', { name: /项目设计画布/ }).waitFor()
    await page.locator('[data-card]').first().waitFor()
    check(await page.locator('[data-card]').count() === 2, 'selected references enter original vendor canvas')
    await page.locator('[data-card]').first().click()
    const archiveButton = page.getByRole('button', { name: /归档选中图/ })
    check(await archiveButton.isEnabled(), 'canvas selected image can be archived')
    await archiveButton.click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1')).some(p => p.assets.some(a => a.provenance?.provider === '项目设计画布 · 人工选定归档')))
    let design = (await read()).assets.find(a => a.provenance?.provider === '项目设计画布 · 人工选定归档')
    check(design.taskId === taskId && design.kind === '款式设计', 'canvas result returns to original task as style')
    const adoptedBefore = design.adopted
    await archiveButton.click()
    await page.waitForFunction(id => JSON.parse(localStorage.getItem('hyy-odm-projects-v1')).some(p => p.assets.some(a => a.id === id && a.revisions.length === 2)), design.id)
    design = (await read()).assets.find(a => a.id === design.id)
    check(design.adopted === adoptedBefore, 're-archive appends revision without auto-adoption')
    await page.screenshot({ path: `${out}/02-canvas.png` })
    await page.getByRole('button', { name: '保存并返回任务', exact: true }).click()
    await page.getByRole('heading', { name: /项目设计画布/ }).waitFor({ state: 'hidden' })
    check(!!(await task()).canvas.blobKey, 'canvas draft persists in IndexedDB')
    await page.reload()
    await page.getByRole('button', { name: '继续设计画布', exact: true }).click()
    await page.locator('[data-card]').first().waitFor()
    check(await page.locator('[data-card]').count() === 2, 'canvas references survive full reload')
    await page.getByRole('button', { name: '不保存退出', exact: true }).click()
    check(await page.getByRole('heading', { name: '退出画布？', exact: true }).isVisible(), 'discard requires confirmation')
    await page.getByRole('button', { name: '继续编辑', exact: true }).click()
    await page.getByRole('button', { name: '保存并返回任务', exact: true }).click()
    await page.getByRole('heading', { name: /项目设计画布/ }).waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: /搜款搜料 ·/ }).click()
    check((await task()).searches[0].selected.length === 2, 'result selection survives reload')
    await page.getByLabel('检索对象', { exact: true }).selectOption('面辅料')
    await page.getByLabel('检索描述', { exact: true }).fill('')
    await page.getByRole('button', { name: '检索本地候选', exact: true }).click()
    check((await task()).searches[0].results.length === 3, 'material candidates are separate from styles')
    await page.getByTestId('search-workspace').getByRole('checkbox').first().check()
    await page.getByRole('button', { name: '归档所选', exact: true }).click()
    const material = (await read()).assets.find(a => a.kind === '面辅料')
    check(!!material && material.provenance.demo, 'material archive retains demo provenance')
    await page.getByLabel('数据范围', { exact: true }).selectOption('外部')
    await page.getByRole('button', { name: '建立外部检索任务', exact: true }).click()
    check((await task()).searches[0].results.length === 0, 'unconnected external search does not fabricate results')
    await page.getByRole('button', { name: '手动收录外部参考', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('参考名称 *', { exact: true }).fill('外部供应商资料')
    await dialog.getByLabel('来源平台 / 供应商 *', { exact: true }).fill('测试供应商')
    await dialog.getByLabel('来源链接（可选）', { exact: true }).fill('javascript:alert(1)')
    await dialog.getByLabel('参考文件 *', { exact: true }).setInputFiles({ name: '材料说明.txt', mimeType: 'text/plain', buffer: Buffer.from('真实上传文件，采购条件待确认') })
    await dialog.getByRole('button', { name: '加入结果集', exact: true }).click()
    check(await dialog.getByRole('alert').isVisible(), 'unsafe external source URL rejected')
    await dialog.getByLabel('来源链接（可选）', { exact: true }).fill('https://example.com/material')
    await dialog.getByRole('button', { name: '加入结果集', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    check((await task()).searches[0].results[0].provenance.scope === '外部', 'external manual record retains source')
    check(!(await read()).assets.some(a => a.name === '外部供应商资料'), 'manual external record still not auto-archived')
    await page.getByRole('button', { name: '返回任务对话', exact: true }).click()
    await page.getByRole('tab', { name: '资产', exact: true }).click()
    await page.getByRole('button', { name: new RegExp(design.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).filter({ hasText: '款式设计 · 任务产出' }).click()
    dialog = page.getByRole('dialog')
    const downloaded = page.waitForEvent('download')
    await dialog.getByRole('button', { name: '下载此版本', exact: true }).click()
    const file = await downloaded, bytes = await fs.readFile(await file.path())
    check(bytes.subarray(1, 4).toString() === 'PNG', 'canvas export downloads real PNG bytes')
    await dialog.getByLabel('从项目面辅料中选择', { exact: true }).selectOption(material.id)
    await dialog.getByRole('button', { name: '添加关联', exact: true }).click()
    await dialog.getByLabel(`${material.name} · 用料角色`, { exact: true }).selectOption('主料')
    await dialog.getByLabel(`${material.name} · 使用部位 / 用量`, { exact: true }).fill('衣身，单耗待确认')
    await dialog.getByRole('button', { name: '保存选料关联', exact: true }).click()
    design = (await read()).assets.find(a => a.id === design.id)
    check(design.materials[0].revision.id === material.adopted, 'material association freezes selected revision')
    await dialog.screenshot({ path: `${out}/03-material-links.png` })
    await dialog.getByRole('button', { name: '选入交付', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.getByRole('tab', { name: '交付', exact: true }).click()
    await page.getByLabel(`${design.name}内部选款`, { exact: true }).selectOption('保留')
    await page.getByRole('button', { name: '内部确认与交接', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('checkbox').last().check()
    await dialog.getByRole('button', { name: '确认并模拟交接', exact: true }).click()
    const handoff = (await read()).handoffs[0]
    check(handoff.items.find(a => a.assetId === design.id).materials[0].usage === '衣身，单耗待确认', 'handoff snapshot includes style-material relation')
    check(!errors.length, `no runtime errors: ${errors.join('; ')}`)
    console.log(`Completed ${n} checks`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
