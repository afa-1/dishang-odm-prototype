const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { chromium } = require('/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const base = (process.env.PROJECT_TEST_URL || 'http://127.0.0.1:4173').replace(/\/$/, '')
const output = '/Users/mac/Desktop/迪尚ODM/tmp/zara-case-check'
