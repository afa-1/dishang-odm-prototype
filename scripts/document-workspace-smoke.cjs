const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const JSZip = require('jszip')
const { chromium } = require('/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
let n = 0
const check = (v, label) => { assert.ok(v, label); console.log('PASS', label); n++ }
const out = '/Users/mac/Desktop/迪尚ODM/tmp/document-workspace-check'
;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true })
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('dialog', d => d.accept())
    await page.goto('http://127.0.0.1:4173/?view=projects&project=demo-summer-trench')
    const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1')).find(p => p.id === 'demo-summer-trench'))
    const olderTask = (await read()).tasks[0].id
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    await page.getByRole('dialog').getByLabel('这次需要完成什么？ *', { exact: true }).fill('整理企划和客户需求')
    await page.getByRole('dialog').getByRole('button', { name: '创建任务', exact: true }).click()
    await page.getByRole('heading', { name: '整理企划和客户需求', exact: true }).waitFor()
    const taskURL = page.url(), taskId = new URL(taskURL).searchParams.get('task')
    const task = async () => (await read()).tasks.find(t => t.id === taskId)
    await page.getByRole('button', { name: '调用技能 / 专家 / 专家团', exact: true }).click()
    const picker = page.getByRole('dialog')
    await picker.getByRole('button', { name: /客户 Brief 拆解/ }).click()
    await picker.getByLabel('本次调用要求 *', { exact: true }).fill('拆解 Brief 并明确未确认事项')
    await picker.locator('summary').filter({ hasText: '引用项目资产' }).click()
    await picker.getByRole('checkbox').first().check()
    await picker.getByRole('button', { name: '加入当前任务', exact: true }).click()
    await page.getByRole('button', { name: '打开Brief 拆解工作稿', exact: true }).click()
    check(await page.getByTestId('document-workspace').getByText('拆解 Brief 并明确未确认事项', { exact: true }).isVisible(), 'workdoc preserves originating capability instructions')
    check(await page.getByRole('button', { name: '导出报告并归档', exact: true }).isDisabled(), 'blank workdoc cannot export')
    await page.getByLabel('段落 1 内容', { exact: true }).fill('客户要求：轻量风衣，目标成本与交期待确认。')
    check(await page.getByRole('button', { name: '设为项目需求', exact: true }).isDisabled(), 'unconfirmed Brief cannot become project requirements')
    await page.getByRole('button', { name: '确认本稿', exact: true }).click()
    check((await task()).documents[0].refs[0].revisionId === (await task()).invocations[0].refs[0].revisionId, 'workdoc inherits invocation references, not unrelated task assets')
    await page.getByRole('button', { name: '设为项目需求', exact: true }).click()
    check((await read()).requirements.sections[0].body.includes('轻量风衣'), 'confirmed Brief explicitly updates project requirements')
    check(!(await read()).tasks.find(t => t.id === olderTask).context.requirements, 'historical task background is not rewritten')
    await page.getByLabel('段落 1 内容', { exact: true }).fill('修改后未确认的需求')
    check(await page.getByRole('button', { name: '设为项目需求', exact: true }).isDisabled(), 'editing invalidates workdoc confirmation')
    check((await read()).requirements.sections[0].body.includes('轻量风衣'), 'workdoc edits do not silently replace confirmed project requirements')
    await page.getByRole('button', { name: '返回任务对话', exact: true }).click()
    check(await page.getByRole('heading', { name: '离开工作稿？', exact: true }).isVisible(), 'unsaved workdoc return requires confirmation')
    await page.getByRole('button', { name: '放弃未保存修改并返回', exact: true }).click()
    await page.getByRole('button', { name: '全部任务', exact: true }).click()
    await page.getByRole('button', { name: '新建任务', exact: true }).click()
    await page.getByRole('dialog').getByLabel('这次需要完成什么？ *', { exact: true }).fill('基于已确认需求继续设计')
    await page.getByRole('dialog').getByRole('button', { name: '创建任务', exact: true }).click()
    await page.getByRole('heading', { name: '基于已确认需求继续设计', exact: true }).waitFor()
    const newTaskId = new URL(page.url()).searchParams.get('task')
    check((await read()).tasks.find(t => t.id === newTaskId).context.requirements.sections[0].body.includes('轻量风衣'), 'new task snapshots confirmed requirements')
    await page.goto(taskURL)
    await page.getByRole('button', { name: '趋势报告', exact: true }).click()
    await page.getByLabel('稿件标题 *', { exact: true }).fill('春夏风衣趋势报告')
    await page.getByLabel('段落 1 内容', { exact: true }).fill('基于资料的观察 <script>window.testInjected=true</script>，不是自动分析。')
    await page.getByTestId('document-workspace').locator('summary').click()
    await page.getByTestId('document-workspace').getByRole('checkbox').nth(1).check()
    await page.getByRole('button', { name: '预览排版', exact: true }).click()
    const frame = page.frameLocator('iframe[title="报告内容预览"]')
    await frame.getByRole('heading', { name: '春夏风衣趋势报告', exact: true }).waitFor()
    check(await frame.locator('script').count() === 0, 'HTML export escapes user markup')
    check(await page.getByRole('dialog').locator('iframe').getAttribute('sandbox') === '', 'report preview is sandboxed')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '导出报告并归档', exact: true }).click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1'))[0].assets.some(a => a.name === '春夏风衣趋势报告 · HTML'))
    let report = (await read()).assets.find(a => a.name === '春夏风衣趋势报告 · HTML')
    check(report.taskId === taskId && !!report.revisions[0].blobKey, 'report stores actual file under originating task')
    const firstRevision = report.adopted
    await page.getByRole('button', { name: '导出报告并归档', exact: true }).click()
    await page.waitForFunction(id => JSON.parse(localStorage.getItem('hyy-odm-projects-v1'))[0].assets.find(a => a.id === id).revisions.length === 2, report.id)
    report = (await read()).assets.find(a => a.id === report.id)
    check(report.adopted === firstRevision, 're-export creates revision without auto-adoption')
    await page.getByRole('button', { name: '返回任务对话', exact: true }).click()
    await page.getByRole('button', { name: '企划 PPT', exact: true }).click()
    await page.getByLabel('稿件标题 *', { exact: true }).fill('夏季风衣系列企划')
    await page.getByLabel('段落 1 内容', { exact: true }).fill('城市与轻户外之间：轻量结构、便捷穿脱、可采购的棉锦面料。')
    await page.getByTestId('document-workspace').locator('summary').click()
    const styles = (await read()).assets.filter(a => a.kind === '款式设计')
    await page.getByTestId('document-workspace').getByRole('checkbox', { name: new RegExp(styles[0].name) }).check()
    await page.getByRole('button', { name: '确认本稿', exact: true }).click()
    await page.getByRole('button', { name: '导出 PPT 并归档', exact: true }).click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('hyy-odm-projects-v1'))[0].assets.some(a => a.name === '夏季风衣系列企划 · PPTX'))
    const deck = (await read()).assets.find(a => a.name === '夏季风衣系列企划 · PPTX')
    check(deck.revisions[0].mime === 'application/vnd.openxmlformats-officedocument.presentationml.presentation', 'PPT is a real PPTX artifact')
    await page.getByLabel('稿件标题 *', { exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: out + '/01-planning-workspace.png' })
    await page.getByRole('button', { name: '返回任务对话', exact: true }).click()
    await page.getByRole('button', { name: /夏季风衣系列企划 · PPTX/ }).click()
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('dialog').getByRole('button', { name: '下载此版本', exact: true }).click()
    const download = await downloadEvent, bytes = await fs.readFile(await download.path())
    const zip = await JSZip.loadAsync(bytes)
    const slidePaths = Object.keys(zip.files).filter(f => /^ppt\/slides\/slide\d+\.xml$/.test(f))
    const xml = (await Promise.all(slidePaths.map(f => zip.file(f).async('string')))).join('')
    check(slidePaths.length >= 7 && xml.includes('城市与轻户外之间') && xml.includes('<a:t>'), 'PPT contains editable slide text')
    check(Object.keys(zip.files).some(f => f.startsWith('ppt/media/') && !zip.files[f].dir), 'PPT embeds selected reference image')
    await download.saveAs(out + '/planning-export.pptx')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: /春夏风衣趋势报告 · HTML/ }).click()
    await page.locator('iframe[title="HTML 报告预览"]').waitFor()
    await page.locator('iframe[title="HTML 报告预览"]').hover()
    check(await page.locator('iframe[title="HTML 报告预览"]').count() === 1, 'tooltip preserves iframe accessible title on hover')
    await page.frameLocator('iframe[title="HTML 报告预览"]').getByRole('heading', { name: '引用素材', exact: true }).waitFor()
    await page.frameLocator('iframe[title="HTML 报告预览"]').locator('footer').waitFor()
    check(true, 'archived report preview includes content after embedded images without truncation')
    const htmlEvent = page.waitForEvent('download')
    await page.getByRole('dialog').getByRole('button', { name: '下载此版本', exact: true }).click()
    const htmlDownload = await htmlEvent, html = await fs.readFile(await htmlDownload.path(), 'utf8')
    check(html.includes('&lt;script&gt;') && html.includes('引用素材'), 'downloaded HTML retains escaped content and sources')
    await page.keyboard.press('Escape')
    await page.reload()
    check((await task()).documents.length === 3 && !!(await task()).documents.find(d => d.kind === '企划 PPT').confirmedAt, 'all three workdoc states persist after reload')
    check(errors.length === 0, 'no browser runtime errors: ' + errors.join('; '))
    console.log('DONE', n, 'checks')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
